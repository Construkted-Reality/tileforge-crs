#!/usr/bin/env python3
# ABOUTME: Generates the EPSG area-of-use table from the crs-definitions catalogue.
# ABOUTME: Reads the BBOX of each WKT definition; needs only the Python standard library.
"""Generate `src/area_of_use_table.rs`.

Each WKT definition of the crs-definitions catalogue states the EPSG area of
use of its CRS as `BBOX[south,west,north,east]` in degrees with two decimals.
A definition with several usages has several boxes; the table holds their
union. A box whose west bound is greater than its east bound crosses the
antimeridian.

Usage:
    python3 tools/gen_area_of_use.py <crs-definitions>/src/defs.rs <repo root>
"""

import re
import sys
from pathlib import Path

DEF_LINE = re.compile(r'^EPSG_(\d+)\|(\d+)\|"[^"]*"\|r#"(.*)"#\|$')
BBOX = re.compile(r"BBOX\[([-0-9.]+),([-0-9.]+),([-0-9.]+),([-0-9.]+)\]")


def centidegrees(text):
    value = float(text) * 100.0
    rounded = round(value)
    if abs(value - rounded) > 1e-6:
        sys.exit(f"BBOX value {text} is not a multiple of 0.01 degree")
    return rounded


def union(boxes):
    """Union of (south, west, north, east) boxes in centidegrees."""
    south = min(b[0] for b in boxes)
    north = max(b[2] for b in boxes)
    crossing = [b for b in boxes if b[1] > b[3]]
    if not crossing:
        return south, min(b[1] for b in boxes), north, max(b[3] for b in boxes)
    if len(crossing) != len(boxes):
        sys.exit("cannot unite a box that crosses the antimeridian with one that does not")
    return south, min(b[1] for b in boxes), north, max(b[3] for b in boxes)


def main():
    defs_path, repo = sys.argv[1], Path(sys.argv[2])
    rows = []
    total = 0
    for line in Path(defs_path).read_text(encoding="utf-8").splitlines():
        m = DEF_LINE.match(line)
        if not m:
            continue
        total += 1
        boxes = [tuple(centidegrees(v) for v in b) for b in BBOX.findall(m.group(3))]
        if boxes:
            south, west, north, east = union(boxes)
            rows.append((int(m.group(2)), west, south, east, north))
    rows.sort()

    out = [
        "// ABOUTME: EPSG area of use of each catalogue CRS as a geographic bounding box.",
        "// ABOUTME: Generated by tools/gen_area_of_use.py; do not edit by hand.",
        f"//! Source: the WKT `BBOX` of {len(rows)} of the {total} crs-definitions entries.",
        "//!",
        "//! Each row is `(EPSG code, [west, south, east, north])` in hundredths of a",
        "//! degree, sorted by code. `west > east` means that the box crosses the",
        "//! antimeridian.",
        "",
        "#[rustfmt::skip]",
        f"pub(crate) static AREAS_OF_USE: [(u16, [i16; 4]); {len(rows)}] = [",
    ]
    for i in range(0, len(rows), 4):
        out.append("    " + " ".join(f"({c}, [{w}, {s}, {e}, {n}])," for c, w, s, e, n in rows[i:i + 4]))
    out.append("];")
    (repo / "src" / "area_of_use_table.rs").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"catalogue definitions: {total}; with an area of use: {len(rows)}")


if __name__ == "__main__":
    main()
