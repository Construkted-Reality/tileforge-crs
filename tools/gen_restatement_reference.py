#!/usr/bin/env python3
# ABOUTME: Generates the PROJ reference fixture for catalogue CRSs that need no datum shift
# ABOUTME: but whose definition proj4rs misreads (the scale factor written as +k_0=).
"""Generate `tests/fixtures/restatement-reference.txt`.

proj4rs 0.1.10 reads the projection scale factor from `+k=` only. The
crs-definitions catalogue writes `+k_0=` in a number of definitions whose
scale factor is not 1. For a CRS in the datum shift table the crate already
restates the definition. This fixture covers the CRSs outside that table: the
low-distortion projections of NAD83 (Oregon, Montana, Wisconsin, Kansas and
others) are the main group.

The reference is the inverse projection that PROJ computes with the EPSG
definition of the CRS, to the geographic CRS of the same datum. The latitude
and longitude are then placed on the WGS 84 ellipsoid, as the crate does for
every CRS that needs no datum shift.

Usage:
    python tools/gen_restatement_reference.py <crs-definitions>/src/defs.rs <repo root>

Requirements: pyproj. The reference is a projection, not a datum
transformation, so grid files and the PROJ network have no effect.
"""

import importlib.util
import re
import sys
from pathlib import Path

import pyproj
from pyproj import CRS, Transformer

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("gen_datum_shifts", HERE / "gen_datum_shifts.py")
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)


def table_codes(table_path):
    """Codes that the datum shift table shifts or refuses."""
    text = Path(table_path).read_text(encoding="utf-8")
    shifted = {int(c) for c in re.findall(r"\((\d+), \d+\)", text)}
    start = text.index("static CRS_WITHOUT_SHIFT")
    body = text[text.index("= [", start) + 3:text.index("];", start)]
    refused = {int(c) for c in re.findall(r"\d+", body)}
    return shifted | refused


def misread_scale_factor(proj4):
    params = gen.proj_params(proj4)
    return "k_0" in params and "k" not in params


def main():
    defs_path, root = Path(sys.argv[1]), Path(sys.argv[2])
    catalogue = gen.read_catalogue(defs_path)
    excluded = table_codes(root / "src/datum_shift_table.rs")
    rows = []
    for code in sorted(catalogue):
        proj4 = catalogue[code]
        if code in excluded or not misread_scale_factor(proj4):
            continue
        crs = CRS.from_epsg(code)
        if not crs.is_projected or crs.area_of_use is None:
            continue
        forward = Transformer.from_crs(crs.geodetic_crs, crs, always_xy=True)
        for lon, lat, height in gen.sample_lonlat(crs.area_of_use.bounds):
            x, y = forward.transform(lon, lat)
            ecef = gen.geodetic_to_ecef(lon, lat, height)
            rows.append((code, x, y, height, *ecef))
    out = root / "tests/fixtures/restatement-reference.txt"
    with out.open("w", encoding="utf-8") as f:
        f.write("# Reference positions for catalogue CRSs without a datum shift whose definition\n")
        f.write("# writes the scale factor as +k_0=. Generated by tools/gen_restatement_reference.py\n")
        f.write(f"# with pyproj {pyproj.__version__}, PROJ {pyproj.proj_version_str}, "
                f"crs-definitions catalogue with {len(catalogue)} definitions.\n")
        f.write("# Each row is one source coordinate and its EPSG:4978 position: the PROJ inverse\n")
        f.write("# projection, placed on the WGS 84 ellipsoid.\n")
        f.write("# Format: epsg src_x src_y src_z ecef_x ecef_y ecef_z\n")
        for row in rows:
            f.write(" ".join(repr(v) for v in row) + "\n")
    print(f"{len(rows)} rows for {len({r[0] for r in rows})} CRSs")


if __name__ == "__main__":
    main()
